import { z } from "zod";

const plainText = z.string().transform((text) =>
  text
    .replace(/\s*\(\[[^\]]*\]\(https?:\/\/[^)]*\)\)/g, "")
    .replace(/\[([^\]]+)\]\(https?:\/\/[^)]*\)/g, "$1")
    .trim(),
);
export const resourceSchema = z.object({
  id: z.string(),
  name: plainText,
  description: plainText,
  url: z
    .string()
    .url()
    .refine((url) => url.startsWith("https://")),
  type: z.enum(["API", "Dataset"]),
  category: z.string(),
  access: z.enum(["No key", "API key", "Unknown"]),
  pricing: z.enum(["Free", "Free tier"]),
  format: z.string(),
  limitation: plainText,
  evidenceUrl: z
    .string()
    .url()
    .refine((url) => url.startsWith("https://"))
    .optional(),
  evidenceNote: plainText.optional(),
  verifiedAt: z
    .string()
    .regex(/^\d{4}-\d{2}-\d{2}$/)
    .optional(),
});
