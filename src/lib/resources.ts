export function sourceNumber(resource: Resource) {
  return String(resources.findIndex((item) => item.id === resource.id) + 1).padStart(3, "0");
}

export function filterResources(
  items: Resource[],
  filters: { type: string; category: string; noKey: boolean; fullyFree: boolean },
) {
  return items.filter(
    (r) =>
      (filters.type === "All" || r.type === filters.type) &&
      (filters.category === "All categories" || r.category === filters.category) &&
      (!filters.noKey || r.access === "No key") &&
      (!filters.fullyFree || r.pricing === "Free"),
  );
}

// Some merged entries only carry the generic placeholder limitation. Treat
// them as "license unspecified" so the UI can flag them transparently.
const GENERIC_LIMITATION = "check the site for current terms";
export function licenseSpecified(resource: Pick<Resource, "limitation">): boolean {
  return !resource.limitation.toLowerCase().includes(GENERIC_LIMITATION);
}

// Relevance scoring for catalog search: name hits outrank description hits,
// which outrank metadata hits. Every word must match somewhere (AND search).
function normalizeSearchText(value: string) {
  return value
    .toLowerCase()
    .normalize("NFKC")
    .replace(/[\p{Pd}_]+/gu, "");
}

export function searchResources(term: string): Resource[] {
  const words = term.split(/\s+/).map(normalizeSearchText).filter(Boolean);
  if (!words.length) return [];
  const scored: { resource: Resource; score: number }[] = [];
  for (const r of resources) {
    const name = normalizeSearchText(r.name);
    const description = normalizeSearchText(r.description);
    const meta = normalizeSearchText(`${r.category} ${r.type} ${r.limitation}`);
    let score = 0;
    let matched = true;
    for (const word of words) {
      if (name.includes(word)) score += name.startsWith(word) ? 6 : 4;
      else if (description.includes(word)) score += 2;
      else if (meta.includes(word)) score += 1;
      else {
        matched = false;
        break;
      }
    }
    if (matched) scored.push({ resource: r, score });
  }
  return scored
    .sort((a, b) => b.score - a.score || a.resource.name.localeCompare(b.resource.name))
    .map((entry) => entry.resource);
}
